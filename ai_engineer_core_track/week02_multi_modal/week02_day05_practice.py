def generate_image(city):
    image_response = openai_client.images.generate(
        model='gpt-image-1-mini',
        prompt=f"Please create an image for {city} containing major tourist areas and attractions of the {city}, meant to be shown to a person who is planning to travel to the {city}.",
        size="1024x1024"
    )

    image_base64 = image_response.data[0].b64_json #type: ignore
    image_data = base64.b64decode(image_base64) #type: ignore
    image = Image.open(BytesIO(image_data))
    return image


